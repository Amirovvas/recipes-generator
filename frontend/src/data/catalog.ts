export const findDish = (slug: string | undefined) => dishes.find((d) => d.slug === slug)

export const formatTime = (minutes: number) => {
  if (minutes < 60) return `${minutes} мин`
  const h = Math.floor(minutes / 60)
  const m = minutes % 60
  return m ? `${h} ч ${m} мин` : `${h} ч`
}
